document.addEventListener('DOMContentLoaded', () => {
    const copilotOrb = document.getElementById('copilot-orb');
    const copilotWindow = document.getElementById('copilot-window');
    const copilotClose = document.getElementById('copilot-close');
    const copilotInput = document.getElementById('copilot-input');
    const copilotSend = document.getElementById('copilot-send');
    const copilotBody = document.getElementById('copilot-body');
    const typingIndicator = document.getElementById('copilot-typing');

    let chatHistory = [];
    let isOpen = false;

    // Toggle Chat Window
    function toggleChat() {
        isOpen = !isOpen;
        if (isOpen) {
            copilotWindow.classList.add('active');
            copilotOrb.setAttribute('aria-expanded', 'true');
            copilotWindow.setAttribute('aria-hidden', 'false');
            if (chatHistory.length === 0) {
                // Initial greeting already in HTML, but we can focus input
                setTimeout(() => copilotInput.focus(), 400);
            }
        } else {
            copilotWindow.classList.remove('active');
            copilotOrb.setAttribute('aria-expanded', 'false');
            copilotWindow.setAttribute('aria-hidden', 'true');
        }
    }

    copilotOrb.addEventListener('click', toggleChat);
    copilotClose.addEventListener('click', toggleChat);

    // Simple markdown parser
    function parseMarkdown(text) {
        let html = text;
        // Bold
        html = html.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
        // Italic
        html = html.replace(/\*(.*?)\*/g, '<em>$1</em>');
        // Links
        html = html.replace(/\[(.*?)\]\((.*?)\)/g, '<a href="$2" target="_blank" style="color: var(--c-amber); text-decoration: underline;">$1</a>');
        // Newlines
        html = html.replace(/\n\n/g, '</p><p>');
        html = html.replace(/\n/g, '<br>');
        // Lists (very basic)
        html = html.replace(/- (.*?)<br>/g, '<li>$1</li>');
        return `<p>${html}</p>`.replace(/<p><\/p>/g, '');
    }

    function addMessage(role, content) {
        const msgDiv = document.createElement('div');
        msgDiv.className = `copilot-msg ${role}`;
        
        if (role === 'ai') {
            msgDiv.innerHTML = parseMarkdown(content);
        } else {
            msgDiv.textContent = content; // secure user input
        }

        // Insert before typing indicator
        copilotBody.insertBefore(msgDiv, typingIndicator);
        scrollToBottom();

        // Attach event listeners for any navigation buttons generated by AI
        if (role === 'ai') {
            const navButtons = msgDiv.querySelectorAll('.copilot-action[data-action="navigate"]');
            navButtons.forEach(btn => {
                btn.addEventListener('click', (e) => {
                    const target = e.target.getAttribute('data-target');
                    if (target) {
                        const targetEl = document.querySelector(target);
                        if (targetEl) {
                            // Automatically close chat window when teleporting on mobile
                            if (window.innerWidth <= 768) {
                                toggleChat();
                            }
                            
                            // Trigger Cinematic Teleportation if available
                            if (typeof TeleportTransition !== 'undefined') {
                                TeleportTransition.go(target, typeof lenis !== 'undefined' ? lenis : null);
                            } else {
                                targetEl.scrollIntoView({ behavior: 'smooth' });
                            }
                        }
                    }
                });
            });
        }
    }

    function scrollToBottom() {
        requestAnimationFrame(() => {
            copilotBody.scrollTop = copilotBody.scrollHeight;
        });
    }

    async function sendMessage(content) {
        if (!content.trim()) return;

        // Add user msg to UI and history
        addMessage('user', content);
        chatHistory.push({ role: 'user', content: content });
        
        copilotInput.value = '';
        typingIndicator.classList.add('active');
        scrollToBottom();

        try {
            const response = await fetch('/api/chat', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify({ messages: chatHistory })
            });

            const data = await response.json();
            
            typingIndicator.classList.remove('active');
            
            if (data.success) {
                addMessage('ai', data.response);
                chatHistory.push({ role: 'ai', content: data.response });
            } else {
                addMessage('ai', `*Error: ${data.error}*`);
            }
        } catch (err) {
            console.error('Chat API Error:', err);
            typingIndicator.classList.remove('active');
            addMessage('ai', '*I am having trouble connecting right now. Please try again later.*');
        }
    }

    // Input handlers
    copilotSend.addEventListener('click', () => {
        sendMessage(copilotInput.value);
    });

    copilotInput.addEventListener('keypress', (e) => {
        if (e.key === 'Enter') {
            sendMessage(copilotInput.value);
        }
    });

    // Quick Actions
    const quickButtons = document.querySelectorAll('.copilot-quick-btn');
    quickButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            const prompt = btn.getAttribute('data-prompt');
            if (prompt) {
                // Hide quick actions after first use
                const qaContainer = document.querySelector('.copilot-quick-actions');
                if (qaContainer) {
                    qaContainer.style.display = 'none';
                }
                sendMessage(prompt);
            }
        });
    });
});
